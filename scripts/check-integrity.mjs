import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'data','bank.json'),'utf8'));
const expected={questions:30068,exams:1201,answers:2325};
const actual={questions:data.questions.length,exams:data.exams.length,answers:Object.keys(data.answers||{}).length};
const ids=new Set(data.questions.map(q=>q.id));
const answerIds=Object.keys(data.answers||{});
const missingAnswerIds=answerIds.filter(id=>!ids.has(id));
const examRefs=data.exams.flatMap(ex=>ex.questionIds||[]);
const missingExamReferences=examRefs.filter(id=>!ids.has(id));
const missingExpected=Object.keys(expected).filter(key=>actual[key]!==expected[key]);
const failures=[];
if(ids.size!==actual.questions)failures.push('Duplicate question IDs');
if(missingAnswerIds.length)failures.push('Answers referencing unknown questions');
if(missingExamReferences.length)failures.push('Exam memberships referencing unknown questions');
if(missingExpected.length)failures.push('Unexpected data record counts: '+missingExpected.join(', '));
const digest=crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'data','bank.json'))).digest('hex');
console.log(JSON.stringify({actual,expected,uniqueIDs:ids.size,examMemberships:examRefs.length,missingAnswerIds:missingAnswerIds.length,missingExamReferences:missingExamReferences.length,sha256:digest,passed:failures.length===0,failures},null,2));
if(failures.length)process.exit(1);
